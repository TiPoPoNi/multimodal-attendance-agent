"""Data models and domain entities.

Defines typed dataclasses and status enumerations for sessions, participants,
tracking events, attendance records, audio metrics, and recommendations.
"""

from __future__ import annotations

from dataclasses import asdict, dataclass, field
from enum import Enum
from typing import Any, Dict, Optional


class SessionStatus(str, Enum):
    """Lifecycle status of an observation session."""

    CREATED = "created"
    ACTIVE = "active"
    PAUSED = "paused"
    COMPLETED = "completed"
    ABORTED = "aborted"


class AttendanceStatus(str, Enum):
    """Presence-based attendance classification."""

    PRESENT = "Present"
    INSUFFICIENT_PRESENCE = "Insufficient Presence"
    NOT_DETECTED = "Not Detected"
    PENDING_CONFIRMATION = "Pending Confirmation"


class NoiseLevel(str, Enum):
    """Estimated background acoustic noise classification."""

    LOW = "low"
    MODERATE = "moderate"
    HIGH = "high"


@dataclass
class Session:
    """Classroom observation session."""

    id: str
    title: str
    start_time: str
    end_time: Optional[str] = None
    duration_seconds: float = 0.0
    status: str = SessionStatus.CREATED.value
    created_at: Optional[str] = None
    updated_at: Optional[str] = None

    def to_dict(self) -> Dict[str, Any]:
        """Convert session object to dictionary."""
        return asdict(self)


@dataclass
class Participant:
    """Participant mapping an anonymous track ID to optional roster information."""

    id: int
    session_id: str
    track_id: int
    roster_name: Optional[str] = None
    student_id: Optional[str] = None
    notes: Optional[str] = None
    created_at: Optional[str] = None

    def to_dict(self) -> Dict[str, Any]:
        """Convert participant object to dictionary."""
        return asdict(self)


@dataclass
class AttendanceRecord:
    """Evaluated attendance record for a participant in a session."""

    id: int
    session_id: str
    participant_id: Optional[int]
    track_id: int
    status: str
    first_seen: Optional[float] = None
    last_seen: Optional[float] = None
    presence_duration_seconds: float = 0.0
    presence_percentage: float = 0.0
    detection_intervals: int = 0
    created_at: Optional[str] = None
    updated_at: Optional[str] = None

    def to_dict(self) -> Dict[str, Any]:
        """Convert attendance record to dictionary."""
        return asdict(self)


@dataclass
class TrackingEvent:
    """A single face detection and tracking frame event."""

    id: int
    session_id: str
    track_id: int
    timestamp: float
    bbox_x: float
    bbox_y: float
    bbox_w: float
    bbox_h: float
    confidence: float
    status: str = "active"

    def to_dict(self) -> Dict[str, Any]:
        """Convert tracking event to dictionary."""
        return asdict(self)


@dataclass
class AudioMetric:
    """Acoustic activity metric computed over an analysis window."""

    id: int
    session_id: str
    timestamp: float
    window_start: float
    window_end: float
    rms_energy: float
    zero_crossing_rate: float
    activity_detected: bool
    noise_level: str

    def to_dict(self) -> Dict[str, Any]:
        """Convert audio metric to dictionary."""
        return asdict(self)


@dataclass
class FusionMetric:
    """Unified multimodal engagement and activity score for a time window."""

    id: int
    session_id: str
    window_start: float
    window_end: float
    visual_presence: float
    audio_activity: float
    movement_level: float
    activity_score: float
    confidence: float
    label: str

    def to_dict(self) -> Dict[str, Any]:
        """Convert fusion metric to dictionary."""
        return asdict(self)


@dataclass
class Recommendation:
    """Contextual pedagogical recommendation generated by rule engine."""

    id: str
    session_id: str
    timestamp: float
    condition: str
    explanation: str
    suggestion: str
    confidence: str
    rule_source: str
    priority: str = "Medium"
    supporting_metrics: Dict[str, Any] = field(default_factory=dict)

    def to_dict(self) -> Dict[str, Any]:
        """Convert recommendation to dictionary."""
        return asdict(self)


